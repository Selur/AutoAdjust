"""Generate the 64x64 blue-noise rank matrix (void-and-cluster, Ulichney 1993) as a C++ header.

Usage: python gen_bluenoise.py ../src/core/bluenoise64.h
"""
import sys

import numpy as np

N = 64
SIGMA = 1.5
SEED = 20261025


def kernel():
    d = np.minimum(np.arange(N), N - np.arange(N)).astype(np.float64)
    g = np.exp(-(d[:, None] ** 2 + d[None, :] ** 2) / (2 * SIGMA * SIGMA))
    return g


K = kernel()


def energy(pattern):
    return np.real(np.fft.ifft2(np.fft.fft2(pattern) * np.fft.fft2(K)))


def shifted(y, x):
    return np.roll(np.roll(K, y, axis=0), x, axis=1)


def tightest_cluster(pattern, e):
    return np.unravel_index(np.argmax(np.where(pattern, e, -np.inf)), pattern.shape)


def largest_void(pattern, e):
    return np.unravel_index(np.argmin(np.where(pattern, np.inf, e)), pattern.shape)


def main(out_path):
    rng = np.random.default_rng(SEED)
    ones = N * N // 10
    pattern = np.zeros((N, N), bool)
    pattern.flat[rng.choice(N * N, ones, replace=False)] = True

    # Initial binary pattern: move points from the tightest cluster into the largest void until stable.
    e = energy(pattern)
    while True:
        cy, cx = tightest_cluster(pattern, e)
        pattern[cy, cx] = False
        e -= shifted(cy, cx)
        vy, vx = largest_void(pattern, e)
        if (vy, vx) == (cy, cx):
            pattern[cy, cx] = True
            e += shifted(cy, cx)
            break
        pattern[vy, vx] = True
        e += shifted(vy, vx)

    rank = np.zeros((N, N), np.int32)
    initial, e_initial = pattern.copy(), e.copy()

    # Phase 1: ranks below the initial point count, removing the tightest clusters.
    for r in range(ones - 1, -1, -1):
        y, x = tightest_cluster(pattern, e)
        pattern[y, x] = False
        e -= shifted(y, x)
        rank[y, x] = r

    # Phases 2 and 3: remaining ranks, filling the largest voids.
    pattern, e = initial, e_initial
    for r in range(ones, N * N):
        y, x = largest_void(pattern, e)
        pattern[y, x] = True
        e += shifted(y, x)
        rank[y, x] = r

    assert sorted(rank.flat) == list(range(N * N))
    with open(out_path, "w", newline="\n") as f:
        f.write("// SPDX-License-Identifier: GPL-2.0-or-later\n")
        f.write("// Generated by tools/gen_bluenoise.py - 64x64 blue-noise rank matrix (void-and-cluster).\n")
        f.write("#pragma once\n\n#include <cstdint>\n\n")
        f.write("namespace autoadjust {\n\n")
        f.write(f"inline constexpr uint16_t kBlueNoise64[{N}][{N}] = {{\n")
        for row in rank:
            f.write("  {" + ",".join(str(v) for v in row) + "},\n")
        f.write("};\n\n}  // namespace autoadjust\n")


if __name__ == "__main__":
    main(sys.argv[1])
